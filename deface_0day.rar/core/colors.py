"""Color output utilities."""

import sys


class Colors:
    """ANSI color codes for terminal output."""
    
    RED = "\033[91m"
    GREEN = "\033[92m"
    YELLOW = "\033[93m"
    BLUE = "\033[94m"
    MAGENTA = "\033[95m"
    CYAN = "\033[96m"
    WHITE = "\033[97m"
    DARK = "\033[90m"
    BOLD = "\033[1m"
    RESET = "\033[0m"
    
    _enabled = True
    
    @classmethod
    def disable(cls):
        cls._enabled = False
    
    @classmethod
    def enable(cls):
        cls._enabled = True
    
    @classmethod
    def colorize(cls, text, color):
        if cls._enabled and sys.stdout.isatty():
            return f"{color}{text}{cls.RESET}"
        return str(text)
    
    @classmethod
    def red(cls, text):
        return cls.colorize(text, cls.RED)
    
    @classmethod
    def green(cls, text):
        return cls.colorize(text, cls.GREEN)
    
    @classmethod
    def yellow(cls, text):
        return cls.colorize(text, cls.YELLOW)
    
    @classmethod
    def blue(cls, text):
        return cls.colorize(text, cls.BLUE)
    
    @classmethod
    def cyan(cls, text):
        return cls.colorize(text, cls.CYAN)
    
    @classmethod
    def white(cls, text):
        return cls.colorize(text, cls.WHITE)
    
    @classmethod
    def dark(cls, text):
        return cls.colorize(text, cls.DARK)
    
    @classmethod
    def bold(cls, text):
        return cls.colorize(text, cls.BOLD)
    
    @classmethod
    def success(cls, text):
        return cls.green(f"[+] {text}")
    
    @classmethod
    def error(cls, text):
        return cls.red(f"[!] {text}")
    
    @classmethod
    def warning(cls, text):
        return cls.yellow(f"[?] {text}")
    
    @classmethod
    def info(cls, text):
        return cls.cyan(f"[*] {text}")
    
    @classmethod
    def vulnerable(cls, text):
        return cls.red(text)
    
    @classmethod
    def patched(cls, text):
        return cls.green(text)
    
